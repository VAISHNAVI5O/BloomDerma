package com.bloomderma.api.service;

import com.bloomderma.api.exception.ResourceNotFoundException;
import com.bloomderma.api.model.Report;
import com.bloomderma.api.repository.ReportRepository;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Paths;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;

/** Patients' report files: the file bytes live in the database (see FileStore), the report details in the reports table. */
@Service
public class ReportService {
    private static final Map<String, String> TYPES = Map.of(
            "pdf", "application/pdf", "png", "image/png", "jpg", "image/jpeg", "jpeg", "image/jpeg", "webp", "image/webp");
    private final ReportRepository repo;
    private final FileStore files;

    public ReportService(ReportRepository repo, FileStore files) {
        this.repo = repo; this.files = files;
    }

    public Report store(String patientId, String title, MultipartFile file) {
        if (file == null || file.isEmpty()) throw new IllegalArgumentException("Please choose a file.");
        byte[] data;
        try { data = file.getBytes(); } catch (IOException e) { throw new UncheckedIOException(e); }
        String ext = detect(data);        // the real type is decided by the file CONTENT, not by its name
        if (ext == null) throw new IllegalArgumentException(
                "Only PDF, PNG, JPG or WEBP files are allowed. (Photos in HEIC format must be saved as JPG first.)");
        String original = withExtension(safeName(file.getOriginalFilename()), ext);
        return persist(patientId, title, original, ext, data, null);
    }

    /** Stores a report generated by the system (PDF bytes) for a patient, marked as created by that doctor. */
    public Report storeGenerated(String patientId, String title, String fileName, byte[] pdf, String doctorName) {
        return persist(patientId, title, safeName(fileName), "pdf", pdf, doctorName);
    }

    private Report persist(String patientId, String title, String original, String ext, byte[] data, String createdBy) {
        String cleanTitle = title == null || title.isBlank() ? original : title.trim();
        if (cleanTitle.length() > 100 || cleanTitle.contains("<") || cleanTitle.contains(">"))
            throw new IllegalArgumentException("Title must be at most 100 characters and cannot contain < or >.");
        String stored = files.save(data, TYPES.get(ext), ext);

        Report r = new Report();
        r.setPatientId(patientId); r.setTitle(cleanTitle); r.setOriginalName(original); r.setStoredName(stored);
        r.setContentType(TYPES.get(ext)); r.setSize(data.length); r.setUploadedAt(LocalDateTime.now());
        r.setCreatedBy(createdBy);
        return repo.save(r);
    }

    public List<Report> list(String patientId) { return repo.findByPatientIdOrderByUploadedAtDesc(patientId); }

    public Report get(Long id) {
        return repo.findById(id).orElseThrow(() -> new ResourceNotFoundException("Report " + id + " not found"));
    }

    public byte[] read(Report r) { return files.read(r.getStoredName()); }

    public void delete(Report r) {
        files.delete(r.getStoredName());
        repo.delete(r);
    }

    private static String safeName(String name) {
        if (name == null || name.isBlank()) return "report";
        String base = Paths.get(name.replace('\\', '/')).getFileName().toString();
        return base.replaceAll("[^A-Za-z0-9._ -]", "_");
    }

    /** Works out the file type from its first bytes: "pdf", "png", "jpg", "webp" - or null when it is none of these. */
    static String detect(byte[] d) {
        if (d.length < 12) return null;
        if ((d[0] & 0xFF) == 0x89 && d[1] == 'P' && d[2] == 'N' && d[3] == 'G') return "png";
        if ((d[0] & 0xFF) == 0xFF && (d[1] & 0xFF) == 0xD8) return "jpg";
        if (d[0] == 'R' && d[1] == 'I' && d[2] == 'F' && d[3] == 'F' && d[8] == 'W' && d[9] == 'E' && d[10] == 'B' && d[11] == 'P') return "webp";
        int limit = Math.min(d.length - 4, 1024);                 // the PDF spec allows a few bytes before "%PDF"
        for (int i = 0; i <= limit; i++)
            if (d[i] == '%' && d[i + 1] == 'P' && d[i + 2] == 'D' && d[i + 3] == 'F') return "pdf";
        return null;
    }

    /** "scan.jpeg" + "png" -> "scan.png"; "scan" + "pdf" -> "scan.pdf". */
    static String withExtension(String name, String ext) {
        int dot = name.lastIndexOf('.');
        String base = dot > 0 ? name.substring(0, dot) : name;
        return base + "." + ext;
    }
}
